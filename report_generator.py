
from reportlab.lib import colors
from reportlab.lib.pagesizes import A4
from reportlab.platypus import (
    SimpleDocTemplate, Paragraph, Spacer,
    Table, TableStyle, PageBreak
)
from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle
from reportlab.lib.enums import TA_CENTER
from reportlab.lib.units import inch
from reportlab.lib.colors import HexColor
from io import BytesIO
from datetime import datetime


def generate_report(answers, role):

    if not answers:
        return None

    total_questions = len(answers)

    avg_confidence = sum(
        item.get("confidence_score", 0) for item in answers
    ) / total_questions

    avg_accuracy = sum(
        item.get("accuracy_score", 0) for item in answers
    ) / total_questions

    summary = {
        "Role": role,
        "Total Questions": total_questions,
        "Average Confidence": round(avg_confidence, 2),
        "Average Accuracy": round(avg_accuracy, 2),
        "Date": datetime.now().strftime("%d-%m-%Y %H:%M")
    }

    return answers, summary


def export_report(answers, summary):

    buffer = BytesIO()

    doc = SimpleDocTemplate(
        buffer,
        pagesize=A4,
        rightMargin=40,
        leftMargin=40,
        topMargin=40,
        bottomMargin=40
    )

    styles = getSampleStyleSheet()

    title_style = ParagraphStyle(
        "TitleStyle",
        parent=styles["Title"],
        fontSize=22,
        textColor=HexColor("#172554"),
        alignment=TA_CENTER,
        spaceAfter=15
    )

    heading_style = ParagraphStyle(
        "HeadingStyle",
        parent=styles["Heading2"],
        textColor=HexColor("#1D4ED8"),
        spaceBefore=12,
        spaceAfter=8
    )

    normal_style = styles["BodyText"]

    elements = []

    elements.append(Paragraph(
        "AI INTERVIEW SIMULATOR",
        title_style
    ))

    elements.append(Paragraph(
        "Interview Performance Report",
        ParagraphStyle(
            "Subtitle",
            parent=styles["Normal"],
            alignment=TA_CENTER,
            fontSize=12
        )
    ))

    elements.append(Spacer(1, 25))

    elements.append(Paragraph("Interview Summary", heading_style))

    summary_data = [
        ["Category", "Result"],
        ["Job Role", str(summary["Role"])],
        ["Total Questions", str(summary["Total Questions"])],
        ["Average Confidence", f'{summary["Average Confidence"]}%'],
        ["Average Accuracy", f'{summary["Average Accuracy"]}%'],
        ["Date", str(summary["Date"])]
    ]

    summary_table = Table(
        summary_data,
        colWidths=[220, 230]
    )

    summary_table.setStyle(TableStyle([
        ("BACKGROUND", (0, 0), (-1, 0), HexColor("#172554")),
        ("TEXTCOLOR", (0, 0), (-1, 0), colors.white),
        ("GRID", (0, 0), (-1, -1), 0.5, colors.grey),
        ("PADDING", (0, 0), (-1, -1), 9),
        ("BACKGROUND", (0, 1), (-1, -1), HexColor("#EFF6FF")),
    ]))

    elements.append(summary_table)
    elements.append(Spacer(1, 20))

    elements.append(Paragraph("Question-wise Performance", heading_style))

    for index, item in enumerate(answers, start=1):

        elements.append(Paragraph(
            f"<b>Question {index}:</b> {item.get('question', '')}",
            normal_style
        ))

        elements.append(Spacer(1, 6))

        elements.append(Paragraph(
            f"<b>Answer:</b> {item.get('answer', '')}",
            normal_style
        ))

        elements.append(Spacer(1, 6))

        elements.append(Paragraph(
            f"<b>Confidence Score:</b> {item.get('confidence_score', 0)}%",
            normal_style
        ))

        elements.append(Paragraph(
            f"<b>Accuracy Score:</b> {item.get('accuracy_score', 0)}%",
            normal_style
        ))

        elements.append(Spacer(1, 15))

    elements.append(Spacer(1, 15))

    elements.append(Paragraph(
        "Generated by AI Interview Simulator",
        ParagraphStyle(
            "Footer",
            parent=normal_style,
            alignment=TA_CENTER,
            textColor=colors.grey
        )
    ))

    doc.build(elements)

    buffer.seek(0)

    return buffer.getvalue()
